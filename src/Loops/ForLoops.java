package Loops;

public class ForLoops {
    public static void main(String[] args) {
        for(int i = 0; i <= 100; i++){
            System.out.println(i);
        }
        for(int i = 10; i>=1; i--){
            System.out.println(i);

        }
        for(int i = -1; i >= -5; i--){
            System.out.println(i);

        }
    }

}
